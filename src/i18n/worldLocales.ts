export function buildExtendedTranslations(
  enBase: UiDictionary
): Record<ExtendedLocale, UiDictionary> {
  const result = {} as Record<ExtendedLocale, UiDictionary>;
  (Object.keys(WORLD_LOCALE_OVERRIDES) as ExtendedLocale[]).forEach((code) => {
    result[code] = mergeDictionary(enBase, WORLD_LOCALE_OVERRIDES[code]);
  });
  return result;
}

