type DeepPartial<T> = {
  [K in keyof T]?: T[K] extends (...args: infer A) => infer R
    ? (...args: A) => R
    : T[K] extends Array<infer U>
      ? U[]
      : T[K] extends object
        ? DeepPartial<T[K]>
        : T[K];
};

function mergeDictionary(
  base: UiDictionary,
  override: DeepPartial<UiDictionary>
): UiDictionary {
  return {
    nav: { ...base.nav, ...override.nav },
    hero: {
      ...base.hero,
      ...override.hero,
      presets: { ...base.hero.presets, ...override.hero?.presets },
    },
    partners: { ...base.partners, ...override.partners },
    services: { ...base.services, ...override.services },
    portfolio: {
      ...base.portfolio,
      ...override.portfolio,
      modal: { ...base.portfolio.modal, ...override.portfolio?.modal },
    },
    community: { ...base.community, ...override.community },
    insights: { ...base.insights, ...override.insights },
    proof: { ...base.proof, ...override.proof },
    faq: { ...base.faq, ...override.faq },
    contact: {
      ...base.contact,
      ...override.contact,
      budgetOptions:
        override.contact?.budgetOptions ?? base.contact.budgetOptions,
    },
    newsletter: { ...base.newsletter, ...override.newsletter },
  };
}

